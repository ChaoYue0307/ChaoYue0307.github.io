export const DEFAULT_BASE_URL = 'https://chaoyue0307.github.io/scifi-atlas/';
export const GENERATED_MARKER = '<!-- Generated by scripts/build-static.mjs. Edit the catalogue or generator, not this page. -->';
const SITE_DIR = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SITE_NAME = '科幻创意图谱';
const SOURCE_FIELDS = ['source_url', 'additional_source_url', 'title_source_url', 'constraint_source_url'];
const ENTRY_ID = /^SF\d{3,6}$/;
const PREVIEW_START = '<!-- ATLAS_PREVIEW_START -->';
const PREVIEW_END = '<!-- ATLAS_PREVIEW_END -->';
const FEATURED_IDS = ['SF001', 'SF008', 'SF135', 'SF201'];

function text(value) {
  return Array.isArray(value) ? value.map(text).filter(Boolean).join('\n') : value == null ? '' : String(value).trim();
}

function prose(value) {
  return escapeHTML(text(value)).replace(/\r\n?|\n/g, '<br>');
}

function baseAddress(value) {
  const url = new URL(value);
  if (!['https:', 'http:'].includes(url.protocol) || url.username || url.password || url.search || url.hash) {
    throw new Error('The public base URL must be an absolute HTTP(S) directory URL without credentials, a query or a fragment.');
  }
  if (!url.pathname.endsWith('/')) url.pathname += '/';
  return url.href;
}

/** Validate paths and references before generating any output; source data is never rewritten. */
export function validateCatalog(payload) {
  if (!payload || !Array.isArray(payload.entries) || !payload.entries.length) throw new Error('Expected a non-empty catalogue entries array.');
  const ids = new Set();
  const categories = new Map();
  const required = ['idea', 'category', 'media', 'work_zh', 'work_en', 'author', 'kind', 'premise', 'mechanism', 'implication', 'constraint', 'source_title', 'evidence'];
  for (const entry of payload.entries) {
    if (!entry || !ENTRY_ID.test(entry.id) || ids.has(entry.id)) throw new Error(`Invalid or duplicate entry ID: ${text(entry?.id)}`);
    ids.add(entry.id);
    if (!Number.isInteger(entry.category_no) || entry.category_no < 1) throw new Error(`Invalid category number: ${entry.id}`);
    if (categories.has(entry.category_no) && categories.get(entry.category_no) !== entry.category) throw new Error(`Conflicting category names: ${entry.category_no}`);
    categories.set(entry.category_no, entry.category);
    for (const key of required) if (!text(entry[key])) throw new Error(`Missing ${key}: ${entry.id}`);
    for (const key of SOURCE_FIELDS) {
      const values = Array.isArray(entry[key]) ? entry[key] : [entry[key]];
      for (const value of values) if (value != null && value !== '' && !safeUrl(value)) throw new Error(`Unsafe or invalid source URL in ${entry.id}.${key}`);
    }
    if (!sourceLinks(entry).length) throw new Error(`No usable source: ${entry.id}`);
    if (entry.related_ids != null && !Array.isArray(entry.related_ids)) throw new Error(`related_ids must be an array: ${entry.id}`);
  }
  for (const entry of payload.entries) {
    for (const id of entry.related_ids || []) if (!ids.has(id) || id === entry.id) throw new Error(`Invalid related entry ${id} in ${entry.id}`);
  }
  return payload.entries;
}

function jsonData(value) {
  return JSON.stringify(value).replace(/[<>&\u2028\u2029]/g, character => ({ '<': '\\u003c', '>': '\\u003e', '&': '\\u0026', '\u2028': '\\u2028', '\u2029': '\\u2029' }[character]));
}

function securityPolicy(json) {
  const hash = createHash('sha256').update(json).digest('base64');
  return `default-src 'self'; script-src 'self' 'sha256-${hash}'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src 'self'; manifest-src 'self'; object-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'self'`;
}

