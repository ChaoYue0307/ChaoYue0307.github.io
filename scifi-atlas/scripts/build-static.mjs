/** Produce deterministic, standalone HTML and sitemap strings without side effects. */
export function buildFiles(payload, { baseUrl = DEFAULT_BASE_URL, manifestPath = 'manifest.webmanifest', ogImagePath = '' } = {}) {
  const entries = validateCatalog(payload);
  const base = baseAddress(baseUrl);
  if (!/^[\w./-]+$/.test(manifestPath) || manifestPath.startsWith('/') || manifestPath.split('/').includes('..')) throw new Error('Manifest path must stay within the site directory.');
  const ogImage = ogImagePath ? safeUrl(new URL(ogImagePath, base).href) : '';
  const files = new Map();
  const stats = getStats(entries);
  const ordered = [...entries].sort((a, b) => a.category_no - b.category_no || Number(a.id.slice(2)) - Number(b.id.slice(2)));
  const website = { '@type': 'WebSite', '@id': `${base}#website`, name: SITE_NAME, url: base };
  const catalogUrl = new URL('catalog/', base).href;

  for (const entry of [...entries].sort((a, b) => Number(a.id.slice(2)) - Number(b.id.slice(2)))) {
    const canonical = new URL(`ideas/${entry.id}/`, base).href;
    const schema = { '@context': 'https://schema.org', '@graph': [
      { '@type': 'WebPage', '@id': `${canonical}#webpage`, url: canonical, name: entry.idea, description: entry.premise, inLanguage: 'zh-CN', isPartOf: website,
        about: { '@type': 'CreativeWork', name: cleanWorkTitle(text(entry.work_zh)), alternateName: entry.work_en },
        citation: sourceLinks(entry).map(link => ({ '@type': 'CreativeWork', name: text(link.label), url: link.url })),
        breadcrumb: { '@id': `${canonical}#breadcrumb` } },
      { '@type': 'BreadcrumbList', '@id': `${canonical}#breadcrumb`, itemListElement: [
        { '@type': 'ListItem', position: 1, name: SITE_NAME, item: base },
        { '@type': 'ListItem', position: 2, name: '创意目录', item: catalogUrl },
        { '@type': 'ListItem', position: 3, name: entry.idea, item: canonical },
      ] },
    ] };
    files.set(`ideas/${entry.id}/index.html`, pageHTML({ title: `${entry.idea} · ${SITE_NAME}`, description: entry.premise, canonical, rootPrefix: '../../', page: 'entry', entryId: entry.id, content: staticDetail(entry, entries), schema, version: payload.version, manifestPath, ogImage }));
  }

  const categories = stats.categories;
  const summary = `本版收录 ${entries.length} 条跨媒介科幻设想，按 ${stats.totalCategories} 个主题组织。条目数不等于独立作品、独立母题或首创发明的数量；这是一份代表性目录。`;
  const catalogContent = `<header class="static-index-heading"><p class="detail-kicker">语义索引 · 无需 JavaScript 即可阅读</p><h1>科幻创意目录</h1><p>${escapeHTML(summary)}</p><p><a class="button button-primary" href="../#/explore">使用搜索与筛选</a></p></header>
    <nav class="static-topic-nav" aria-label="全部主题"><ul>${categories.map(category => `<li><a href="#topic-${String(category.value).padStart(2, '0')}"><span>${String(category.value).padStart(2, '0')}</span> ${escapeHTML(category.label)} <span>(${category.count})</span></a></li>`).join('')}</ul></nav>
    ${categories.map(category => `<section class="static-topic-section" id="topic-${String(category.value).padStart(2, '0')}" aria-labelledby="heading-${category.value}"><h2 id="heading-${category.value}">${String(category.value).padStart(2, '0')} ${escapeHTML(category.label)} <span>· ${category.count} 条</span></h2><ul class="static-entry-list">${ordered.filter(entry => entry.category_no === Number(category.value)).map(entry => `<li class="static-index-item"><p class="static-index-meta">${entry.id} · ${escapeHTML(entry.media)}</p><h3><a href="../ideas/${entry.id}/">${escapeHTML(entry.idea)}</a></h3><p class="static-index-work">${escapeHTML(cleanWorkTitle(text(entry.work_zh)))} · ${escapeHTML(entry.author)}</p><p class="static-index-premise">${escapeHTML(entry.premise)}</p></li>`).join('')}</ul></section>`).join('')}`;
  const catalogSchema = { '@context': 'https://schema.org', '@graph': [
    { '@type': 'CollectionPage', '@id': `${catalogUrl}#webpage`, url: catalogUrl, name: '科幻创意目录', description: summary, inLanguage: 'zh-CN', isPartOf: website, mainEntity: { '@id': `${catalogUrl}#entries` } },
    { '@type': 'ItemList', '@id': `${catalogUrl}#entries`, name: '代表性科幻创意条目', numberOfItems: entries.length, itemListElement: ordered.map((entry, i) => ({ '@type': 'ListItem', position: i + 1, name: entry.idea, url: new URL(`ideas/${entry.id}/`, base).href })) },
    { '@type': 'BreadcrumbList', itemListElement: [{ '@type': 'ListItem', position: 1, name: SITE_NAME, item: base }, { '@type': 'ListItem', position: 2, name: '创意目录', item: catalogUrl }] },
  ] };
  files.set('catalog/index.html', pageHTML({ title: `${SITE_NAME}目录 · ${entries.length} 条跨媒介设想`, description: summary, canonical: catalogUrl, rootPrefix: '../', page: 'catalog', content: catalogContent, schema: catalogSchema, version: payload.version, manifestPath, ogImage }));
  const urls = [base, catalogUrl, ...[...entries].sort((a, b) => Number(a.id.slice(2)) - Number(b.id.slice(2))).map(entry => new URL(`ideas/${entry.id}/`, base).href)];
  files.set('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map(url => `  <url><loc>${escapeHTML(url)}</loc></url>`).join('\n')}\n</urlset>\n`);
  return files;
}

export function renderHomePreview(payload) {
  const entries = validateCatalog(payload);
  const byId = new Map(entries.map(entry => [entry.id, entry]));
  const featured = FEATURED_IDS.map(id => byId.get(id)).filter(Boolean);
  return `<p class="static-preview-note">先读这 ${featured.length} 条精选设想，也可<a href="./catalog/">浏览完整目录中的 ${entries.length} 条创意</a>。</p>
${featured.map(entry => {
    const theme = isThemeEvidence(entry);
    const author = text(entry.author).split(/[（(]/)[0].trim();
    return `<article class="idea-row" data-entry="${entry.id}">
  <div class="row-meta"><span class="row-id">${entry.id}</span><span class="row-medium">${escapeHTML(entry.media)}</span></div>
  <div class="row-main"><h3 class="idea-title"><a href="./ideas/${entry.id}/" data-idea="${entry.id}">${escapeHTML(entry.idea)}</a></h3><p class="work-line"><span class="work-title">${escapeHTML(cleanWorkTitle(text(entry.work_zh)))}</span>${author ? `<span class="creator">${escapeHTML(author)}</span>` : ''}</p><p class="idea-premise">${escapeHTML(entry.premise)}</p></div>
  <div class="row-side"><span class="evidence-label${theme ? ' theme-support' : ''}">${theme ? '主题支持 · 待核对' : '直接支持'}</span></div>
</article>`;
  }).join('\n')}`;
}

/** Replace only the agreed preview region, preserving both markers and all surrounding bytes. */
export function updateHomePreview(html, preview) {
  const start = html.indexOf(PREVIEW_START);
  const end = html.indexOf(PREVIEW_END);
  if (start < 0 || end < start || html.lastIndexOf(PREVIEW_START) !== start || html.lastIndexOf(PREVIEW_END) !== end) {
    throw new Error('index.html must contain exactly one ordered ATLAS_PREVIEW_START / ATLAS_PREVIEW_END marker pair.');
  }
  return `${html.slice(0, start + PREVIEW_START.length)}\n${preview}\n${html.slice(end)}`;
}

async function existingText(filename) {
  try { return await readFile(filename, 'utf8'); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

async function staleGeneratedPages(siteDir, expected) {
  let folders;
  try { folders = await readdir(path.join(siteDir, 'ideas'), { withFileTypes: true }); }
  catch (error) { if (error.code === 'ENOENT') return []; throw error; }
  const stale = [];
  for (const folder of folders) {
    if (!folder.isDirectory() || !ENTRY_ID.test(folder.name)) continue;
    const relative = `ideas/${folder.name}/index.html`;
    if (!expected.has(relative) && (await existingText(path.join(siteDir, relative)))?.includes(GENERATED_MARKER)) stale.push(relative);
  }
  return stale.sort();
}

/** --check compares bytes without touching files; normal builds only replace changed generated outputs. */
export async function buildStatic({ siteDir = SITE_DIR, check = false, ...options } = {}) {
  const payload = JSON.parse(await readFile(path.join(siteDir, 'data/catalog.json'), 'utf8'));
  const files = buildFiles(payload, options);
  const home = await readFile(path.join(siteDir, 'index.html'), 'utf8');
  files.set('index.html', updateHomePreview(home, renderHomePreview(payload)));
  const changed = [];
  for (const [relative, content] of files) {
    const filename = path.join(siteDir, relative);
    if (await existingText(filename) === content) continue;
    changed.push(relative);
    if (!check) { await mkdir(path.dirname(filename), { recursive: true }); await writeFile(filename, content, 'utf8'); }
  }
  const stale = await staleGeneratedPages(siteDir, files);
  if (!check) for (const relative of stale) {
    await unlink(path.join(siteDir, relative));
    try { await rmdir(path.dirname(path.join(siteDir, relative))); } catch (error) { if (error.code !== 'ENOTEMPTY') throw error; }
  }
  return { check, ok: !check || (!changed.length && !stale.length), entries: payload.entries.length, generatedFiles: files.size, changed, stale };
}

async function main() {
  const args = process.argv.slice(2);
  const options = {};
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check') options.check = true;
    else if (args[i] === '--base-url' && args[i + 1]) options.baseUrl = args[++i];
    else if (args[i] === '--help') { console.log('Usage: node scripts/build-static.mjs [--check] [--base-url https://host/scifi-atlas/]'); return; }
    else throw new Error(`Unknown or incomplete option: ${args[i]}`);
  }
  const result = await buildStatic(options);
  console.log(JSON.stringify(result, null, 2));
  if (!result.ok) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
