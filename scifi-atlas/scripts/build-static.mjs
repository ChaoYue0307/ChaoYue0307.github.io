function paragraphSection(label, value, modifier = '') {
  if (!text(value)) return '';
  return `<section class="detail-section${modifier ? ` ${modifier}` : ''}"><h2 class="detail-label">${escapeHTML(label)}</h2><p class="detail-text">${prose(value)}</p></section>`;
}

function relationship(entry, other) {
  if ((entry.related_ids || []).includes(other.id) || (other.related_ids || []).includes(entry.id)) return '关联母题';
  return entry.category_no === other.category_no ? '同主题' : '相近子类型';
}

